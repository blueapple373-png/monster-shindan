export function getGuidedGoal(area) {
  return GUIDED_GOALS.find((item) => item.id === area) ?? GUIDED_GOALS[0];
}
export function getGuidedPlan(area, stage) {
  const goal = getGuidedGoal(area);
  const current = goal.stages.find((item) => item.id === stage) ?? goal.stages[0];
  return { task: current.task, actions: [...current.actions], area: goal.id, stage: current.id, label: current.label };
}
